#!/usr/bin/env python3
"""Regenerates crates/plantuml-core/src/tim/themes.rs from crates/plantuml-core/themes/."""
import os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "plantuml-core")
names = sorted(f for f in os.listdir(os.path.join(root, "themes")) if f.startswith("puml-theme-") and f.endswith(".puml"))
out = "//! Themes bundled with the library (`themes/puml-theme-*.puml`); generated by `scripts/gen-themes.py`.\n\npub static THEMES: &[(&str, &str)] = &[\n"
for f in names:
    n = f[len("puml-theme-"):-len(".puml")]
    out += f'    ("{n}", include_str!("../../themes/{f}")),\n'
out += "];\n"
open(os.path.join(root, "src", "tim", "themes.rs"), "w").write(out)
